"use client";
import { useEffect, useRef, useState } from "react";
import { TopBar } from "@/components/TopBar";
import { DigitPanel } from "@/components/DigitPanel";
import { ExecutionPanel } from "@/components/ExecutionPanel";
import { FamilyInsights } from "@/components/FamilyInsights";
import { LoginDrawer } from "@/components/LoginDrawer";
import { MarketTabs } from "@/components/MarketTabs";
import { RealConfirmModal } from "@/components/RealConfirmModal";
import { SignalMatrix } from "@/components/SignalMatrix";
import { TickChart } from "@/components/TickChart";
import { Toast } from "@/components/Toast";
import { TradeConfirmModal } from "@/components/TradeConfirmModal";
import { TradeTables } from "@/components/TradeTables";
import { useAnalysis } from "@/hooks/useAnalysis";
import type { SignalRow } from "@/lib/signals";
import { executeTrade, guardrailBlock, startPublic, switchAccount } from "@/services/session";
import { currentAccount, useStore } from "@/store/useStore";

export default function Home() {
  const [loginOpen, setLoginOpen] = useState(false);
  const [pendingReal, setPendingReal] = useState<string | null>(null);
  const [ticket, setTicket] = useState<SignalRow | null>(null);
  const { output, rows, best } = useAnalysis();
  const autoMode = useStore((s) => s.autoMode);
  const accounts = useStore((s) => s.accounts);
  const isReal = useStore((s) => currentAccount(s)?.account_type === "real");
  const lastAuto = useRef(0);

  useEffect(() => startPublic(), []);

  const requestSwitch = (id: string) => {
    const a = accounts.find((x) => x.account_id === id);
    if (!a) return;
    if (a.account_type === "real") setPendingReal(id);
    else void switchAccount(id);
  };

  const run = (r: SignalRow, stake: number, auto: boolean) =>
    executeTrade({ contractType: r.contractType, barrier: r.barrier, duration: r.duration, stake, pModel: r.pModel, auto });

  // Semi-auto: fire on a fresh actionable signal, max one per 5 s, never while another order is in flight.
  useEffect(() => {
    if (!autoMode || !best) return;
    const s = useStore.getState();
    if (s.busy || guardrailBlock() || Date.now() - lastAuto.current < 5000) return;
    if (s.trades.some((t) => t.status === "open" && t.accountId === s.accountId)) return;
    lastAuto.current = Date.now();
    void run(best, best.kellyStake, true);
  }, [autoMode, best]);

  return (
    <div className={`min-h-screen ${isReal ? "ring-4 ring-inset ring-red-600/60" : ""}`}>
      <TopBar onOpenLogin={() => setLoginOpen(true)} onRequestSwitch={requestSwitch} />
      <main className="mx-auto max-w-[1600px] space-y-4 p-4">
        <MarketTabs />
        <div className="grid gap-4 xl:grid-cols-[minmax(0,1fr)_380px]">
          <div className="min-w-0 space-y-4">
            <TickChart output={output} />
            <div className="grid gap-4 lg:grid-cols-2">
              <DigitPanel digits={(output.insights as { digits: number[] }).digits} />
              <FamilyInsights output={output} />
            </div>
            <SignalMatrix rows={rows} onTrade={setTicket} />
          </div>
          <div className="space-y-4">
            <ExecutionPanel best={best} onExecute={(r, auto) => void run(r, r.kellyStake, auto)} />
            <div className="panel p-4 text-[11px] leading-relaxed text-slate-500">
              <b className="text-slate-300">Model honesty.</b> Synthetic indices are generated by a certified RNG; under that null every
              digit is uniform and every move a fair coin. Deriv payouts (≈95 % on 50/50 contracts) imply a break-even of ≈51.2 %, so a
              signal is only marked actionable when the shrunk model probability beats the live break-even. Expect that to be rare.
            </div>
          </div>
        </div>
        <TradeTables />
      </main>
      <LoginDrawer open={loginOpen} onClose={() => setLoginOpen(false)} />
      {pendingReal && (
        <RealConfirmModal
          accountId={pendingReal}
          onCancel={() => setPendingReal(null)}
          onConfirm={() => {
            useStore.getState().set({ realConfirmed: pendingReal });
            void switchAccount(pendingReal);
            setPendingReal(null);
          }}
        />
      )}
      {ticket && (
        <TradeConfirmModal
          row={ticket}
          onCancel={() => setTicket(null)}
          onConfirm={(stake) => {
            void run(ticket, stake, false);
            setTicket(null);
          }}
        />
      )}
      <Toast />
    </div>
  );
}
